export const searchProducts = ({
  q = '',
  category = '',
  min = 0,
  max = Infinity,
  rating = 0,
  prime = false,
  brand = '',
  discount = 0,
  sort = 'relevance',
} = {}) => {
  const term = q.trim().toLowerCase()
  let list = products.filter((p) => {
    if (category && p.category !== category) return false
    if (p.price < min || p.price > max) return false
    if (rating && p.rating < rating) return false
    if (prime && !p.prime) return false
    if (brand && p.brand !== brand) return false
    if (discount && ((p.mrp - p.price) / p.mrp) * 100 < discount) return false
    if (term) {
      const hay = `${p.title} ${p.brand} ${p.sub} ${p.category} ${p.desc}`.toLowerCase()
      if (!hay.includes(term)) return false
    }
    return true
  })
  switch (sort) {
    case 'price-asc':
      list = [...list].sort((a, b) => a.price - b.price)
      break
    case 'price-desc':
      list = [...list].sort((a, b) => b.price - a.price)
      break
    case 'rating':
      list = [...list].sort((a, b) => b.rating - a.rating)
      break
    case 'reviews':
      list = [...list].sort((a, b) => b.reviews - a.reviews)
      break
    case 'discount':
      list = [...list].sort(
        (a, b) => (b.mrp - b.price) / b.mrp - (a.mrp - a.price) / a.mrp,
      )
      break
    default:
      break
  }
  return list
}

